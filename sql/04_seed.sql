-- ---------------------------------------------------------------------
--  10. 技师排班（近 7 天 × 每技师 4 个时段）
--      原系统 tech_schedule 是空表且零读写，这里填充基础排班，
--      由 app/service.py 在 SPA 预约时占用对应档期。
-- ---------------------------------------------------------------------
INSERT IGNORE INTO `tech_schedule` (tech_id, work_date, time_slot, is_booked)
SELECT t.tech_id, DATE_ADD(CURDATE(), INTERVAL d.n DAY), s.slot, 0
FROM technician t
CROSS JOIN (SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL
            SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6) d
CROSS JOIN (SELECT '09:00' AS slot UNION ALL SELECT '11:00' UNION ALL
            SELECT '14:00' UNION ALL SELECT '16:00') s;
